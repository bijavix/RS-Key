//! The four curves the HSM keeps, as the explicit domain parameters a CV
//! certificate carries. A host names a curve by its parameters, never by an OID,
//! and the driver recognises the one in a response by `p` and `a` alone — so these
//! are the exact byte strings it compares, `p521`'s leading `01` and `secp256k1`'s
//! all-zero `a` included (SEC 2 / FIPS 186-4 values).

use rsk_ec::Curve;

/// One curve's parameters: field prime, coefficients, uncompressed base point,
/// group order and cofactor.
#[derive(Debug, PartialEq, Eq)]
pub(crate) struct Domain {
    pub curve: Curve,
    pub p: &'static [u8],
    pub a: &'static [u8],
    pub b: &'static [u8],
    pub g: &'static [u8],
    pub n: &'static [u8],
    pub h: &'static [u8],
}

impl Domain {
    /// A field element's width, which is also a scalar's here.
    pub(crate) const fn field_len(&self) -> usize {
        self.p.len()
    }

    /// An uncompressed point's width.
    pub(crate) const fn point_len(&self) -> usize {
        1 + 2 * self.p.len()
    }
}

