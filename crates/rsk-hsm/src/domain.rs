/// Every curve, in the order a host is most likely to ask for them.
pub(crate) const ALL: [&Domain; 4] = [&P256, &P384, &P521, &K256];

/// The curve a request names by its prime and first coefficient — the pair the
/// driver identifies a curve by, so the pair this device answers to.
pub(crate) fn by_prime(p: &[u8], a: &[u8]) -> Option<&'static Domain> {
    ALL.into_iter().find(|d| d.p == p && d.a == a)
}

/// The parameters of a curve this applet keeps.
pub(crate) fn of(curve: Curve) -> Option<&'static Domain> {
    ALL.into_iter().find(|d| d.curve == curve)
}

